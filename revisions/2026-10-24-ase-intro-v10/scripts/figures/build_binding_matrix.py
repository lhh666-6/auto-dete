"""Build only Table 3 from the independently checked frozen X2 route data.

python scripts/figures/build_binding_matrix.py [--check]
--check compiles an isolated Springer preview at 31pc in the system temp folder.
No runner, model, or experiment is executed; no other manuscript file is written.
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import shutil
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
MANUSCRIPT = HERE.parents[1]
SOURCE = HERE / "figure-data.json"
TARGET = MANUSCRIPT / "tables/binding-scope.tex"
BINDINGS = ["context", "content", "instance", "content_raw"]
MODES = ["unchecked_live", "verified_read"]
LABELS = {
    "C1-identical-new-instance": r"C1: Identical new instance",
    "C2-effective-date": r"C2: Effective-date change\textsuperscript{a}",
    "C2-cost-center": r"C2: Cost-center change\textsuperscript{a}",
    "C2-effective-date-render-noise": r"C2: Date change + render noise\textsuperscript{a}",
    "C3-referent-mutated": r"C3: Changed external document\textsuperscript{b}",
    "C4-representation": r"C4: Number/string representation",
    "C4-note-display": r"C4: Display-only note",
    "C4-note-semantic": r"C4: Semantic note",
    "C3-referent-unchanged-control": r"C3: Unchanged-document control\textsuperscript{b}",
}


def build():
    source_bytes = SOURCE.read_bytes()
    data = json.loads(source_bytes)
    routes = data["x2_routes"]
    assert len(routes) == 72
    assert set(LABELS) == {case["case_id"] for case in data["x2_cases"]["cases"]}
    assert BINDINGS == data["x2_cases"]["bindings"]
    assert MODES == data["x2_cases"]["executor_modes"]
    index = {(r["case_id"], r["binding"], r["executor_mode"]): r for r in routes}
    assert len(index) == len(routes)
    rendered = []
    for case_id, label in LABELS.items():
        cells = []
        for binding in BINDINGS:
            decisions = [index[case_id, binding, mode]["binding_accepted"] for mode in MODES]
            assert decisions[0] == decisions[1], (case_id, binding, decisions)
            assert decisions[0] in ("True", "False")
            cells.append("A" if decisions[0] == "True" else "R")
        rendered.append("% " + case_id + "\n" + label + " & " + " & ".join(cells) + r" \\")
    omitted_field_cases = [key for key in LABELS if key.startswith("C2-")]
    assert len(omitted_field_cases) == 3
    for case_id in omitted_field_cases:
        for mode in MODES:
            r = index[case_id, "context", mode]
            assert r["binding_accepted"] == "True" and r["actual_effect_count"] == "1" and r["semantic_violation"] == "True"
            for binding in ["content", "instance"]:
                assert index[case_id, binding, mode]["binding_accepted"] == "False"
    for binding in BINDINGS:
        unchecked = index["C3-referent-mutated", binding, "unchecked_live"]
        verified = index["C3-referent-mutated", binding, "verified_read"]
        assert unchecked["binding_accepted"] == verified["binding_accepted"] == "True"
        assert unchecked["actual_amount_decimal2dp"] == "999.00"
        assert verified["actual_effect_count"] == "0" and verified["executor_stop"] == "True"
        for mode in MODES:
            assert index["C3-referent-unchanged-control", binding, mode]["actual_amount_decimal2dp"] == "101.00"
    header = r"""\begin{table}[tbp]
\caption{Binding-gate decisions over nine constructed cases. A: admit; R: reject. Each decision is identical under unchecked and verified execution (72 routes); entries do not report writes. All comparators share the authorized-value check.}\label{tab:binding-scope}
\centering\footnotesize
\setlength{\tabcolsep}{3pt}
\renewcommand{\arraystretch}{1.12}
\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}p{0.46\textwidth}*{4}{>{\centering\arraybackslash}X}@{}}
\toprule
Case & Context & Content & Instance & \shortstack{Raw content\\(diagnostic)} \\
\midrule
"""
    footer = r"""
\bottomrule
\end{tabularx}
\par\smallskip
\begin{minipage}{\textwidth}\footnotesize\raggedright
\textsuperscript{a}These three changes affect fields omitted from the context key. Context admission produces semantic-violating writes under both executors; content and instance binding reject them.\par
\textsuperscript{b}Every binding admits the changed external document. The common verified executor blocks its write; unchecked execution writes 999.00. The unchanged-document control writes 101.00 in both modes.\par
Raw content omits money normalization and is diagnostic. A note is compared when the case declares it semantic.
\end{minipage}
\end{table}
"""
    text = "% Generated by scripts/figures/build_binding_matrix.py\n"
    text += "% FIGURE-DATA.json SHA256: " + hashlib.sha256(source_bytes).hexdigest() + "\n"
    text += header + "\n".join(rendered) + "\n" + footer
    TARGET.write_text(text, encoding="utf-8")
    print(json.dumps({"table": str(TARGET), "fixtures": len(LABELS), "raw_routes_checked": len(routes), "decisions_identical_between_executors": True}))


def check():
    preview = Path(tempfile.mkdtemp(prefix="ase-table3-31pc-"))
    out = preview / "out"
    out.mkdir()
    (preview / ".latexmkrc").write_text(
        "$out_dir = 'out';\nuse File::Copy qw(copy);\n"
        "END { copy('out/table3-check.pdf', 'table3-check.pdf') if -f 'out/table3-check.pdf'; }\n",
        encoding="utf-8")
    source = r"""\documentclass[pdflatex,sn-basic]{sn-jnl}
\usepackage[T1]{fontenc}
\usepackage{lmodern,amsmath,amssymb,booktabs,tabularx}
\setlength{\textwidth}{31pc}
\begin{document}
\pagestyle{empty}
\setcounter{table}{2}
\typeout{TABLE-CHECK-TEXTWIDTH=\the\textwidth}
\input{TABLEPATH}
\end{document}
""".replace("TABLEPATH", TARGET.as_posix())
    (preview / "table3-check.tex").write_text(source, encoding="utf-8")
    env = os.environ.copy()
    env["TEXINPUTS"] = "." + os.pathsep + MANUSCRIPT.as_posix() + os.pathsep + env.get("TEXINPUTS", "")
    args = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "-output-directory=out", str(preview / "table3-check.tex")]
    for i in range(2):
        run = subprocess.run(args, cwd=preview, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        (out / f"pass{i+1}.txt").write_bytes(run.stdout)
        if run.returncode:
            raise RuntimeError(run.stdout.decode("utf-8", errors="replace"))
    log = (out / "table3-check.log").read_text(encoding="utf-8", errors="replace")
    bad = [line for line in log.splitlines() if "Overfull" in line or "Underfull" in line or "Warning" in line]
    shutil.copy2(out / "table3-check.pdf", preview / "table3-check.pdf")
    print(json.dumps({"preview": str(preview), "diagnostics": bad, "textwidth_372pt": "TABLE-CHECK-TEXTWIDTH=372.0pt" in log}))
    try:
        import fitz
        with fitz.open(preview / "table3-check.pdf") as doc:
            doc[0].get_pixmap(dpi=160).save(preview / "preview.png")
        print(str(preview / "preview.png"))
    except ImportError:
        pass


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    build()
    if args.check:
        check()
